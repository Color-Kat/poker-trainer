// ===== Equity: exact enumeration / Monte Carlo, preflop hand order =====
const Equity = (() => {
  const choose = (n, k) => {
    if (k < 0 || k > n) return 0;
    let r = 1;
    for (let i = 1; i <= k; i++) r = (r * (n - k + i)) / i;
    return Math.round(r);
  };

  // Equity of known hands. hands: [[c1,c2], ...]; board: 0..5 cards.
  // opts.toCome: board cards still to deal (default 5 - board.length; e.g. 1 = "only the next card")
  // opts.dead: extra removed cards; opts.exactLimit (default 30000 runouts); opts.iters (MC, default 10000)
  // → { eq: [share 0..1], win: [], tie: [], samples, exact }
  function calc(hands, board, opts = {}) {
    const toCome = opts.toCome ?? 5 - board.length;
    const used = new Set([...hands.flat(), ...board, ...(opts.dead || [])]);
    const deck = Cards.deck().filter((c) => !used.has(c));
    const n = hands.length;
    const eq = new Array(n).fill(0), win = new Array(n).fill(0), tie = new Array(n).fill(0);
    const sc = new Array(n);
    const cardsBuf = hands.map((h) => h.concat(board, new Array(toCome).fill(0)));
    const base = 2 + board.length;
    let samples = 0;

    const run = (extra) => {
      let best = -1, nb = 0;
      for (let i = 0; i < n; i++) {
        const buf = cardsBuf[i];
        for (let j = 0; j < toCome; j++) buf[base + j] = extra[j];
        const s = (sc[i] = HandEval.score(buf));
        if (s > best) { best = s; nb = 1; } else if (s === best) nb++;
      }
      for (let i = 0; i < n; i++) if (sc[i] === best) {
        eq[i] += 1 / nb;
        if (nb === 1) win[i]++; else tie[i]++;
      }
      samples++;
    };

    const total = choose(deck.length, toCome);
    const exact = total <= (opts.exactLimit ?? 30000);
    const extra = new Array(toCome);
    if (exact) {
      const rec = (start, depth) => {
        if (depth === toCome) { run(extra); return; }
        for (let i = start; i <= deck.length - (toCome - depth); i++) { extra[depth] = deck[i]; rec(i + 1, depth + 1); }
      };
      rec(0, 0);
    } else {
      const iters = opts.iters ?? 10000;
      const w = deck.slice();
      for (let it = 0; it < iters; it++) {
        for (let j = 0; j < toCome; j++) {
          const k = j + Math.floor(U.rng() * (w.length - j));
          const t = w[j]; w[j] = w[k]; w[k] = t;
          extra[j] = w[j];
        }
        run(extra);
      }
    }
    const d = samples || 1;
    return { eq: eq.map((x) => x / d), win: win.map((x) => x / d), tie: tie.map((x) => x / d), samples, exact };
  }

  // Hero equity vs nOpp unknown hands (Monte Carlo to the river).
  // opts.iters (default 1000), opts.dead, opts.oppFilter(hole, board) → boolean | weight 0..1
  // (rejection sampling, up to 40 tries per opponent; models "hands this opponent would play this way").
  function vsRandom(hole, board, nOpp, opts = {}) {
    if (nOpp <= 0) return 1;
    const iters = opts.iters ?? 1000;
    const filter = opts.oppFilter || null;
    const used = new Set([...hole, ...board, ...(opts.dead || [])]);
    const w = Cards.deck().filter((c) => !used.has(c));
    const toCome = 5 - board.length;
    const heroBuf = hole.concat(board, new Array(toCome).fill(0));
    const oppBuf = new Array(nOpp).fill(0).map(() => [0, 0].concat(board, new Array(toCome).fill(0)));
    const base = 2 + board.length;
    let total = 0;
    const draw = (pos) => {
      const k = pos + Math.floor(U.rng() * (w.length - pos));
      const t = w[pos]; w[pos] = w[k]; w[k] = t;
      return w[pos];
    };
    for (let it = 0; it < iters; it++) {
      let pos = 0;
      for (let o = 0; o < nOpp; o++) {
        let a, b;
        for (let tries = 0; ; tries++) {
          a = draw(pos); b = draw(pos + 1);
          if (!filter || tries >= 40) break;
          const v = filter([a, b], board);
          const wgt = v === true ? 1 : v === false ? 0 : +v || 0;
          if (wgt >= 1 || (wgt > 0 && U.rng() < wgt)) break;
        }
        oppBuf[o][0] = a; oppBuf[o][1] = b;
        pos += 2;
      }
      for (let j = 0; j < toCome; j++) {
        const c = draw(pos++);
        heroBuf[base + j] = c;
        for (let o = 0; o < nOpp; o++) oppBuf[o][base + j] = c;
      }
      const hs = HandEval.score(heroBuf);
      let best = 0, ties = 0;
      for (let o = 0; o < nOpp; o++) {
        const s = HandEval.score(oppBuf[o]);
        if (s > best) { best = s; ties = s === hs ? 1 : 0; } else if (s === best && s === hs) ties++;
      }
      if (hs > best) total += 1;
      else if (hs === best) total += 1 / (ties + 1);
    }
    return total / iters;
  }

  // 169 starting hands, strongest → weakest. Generated by tools/gen-preflop-order.js
  // (average of rank by equity vs 1 and vs 2 random hands).
  const PREFLOP_ORDER = 'AA KK QQ JJ TT 99 88 AKs AQs AJs AKo 77 AQo ATs KQs AJo KJs A9s 66 KQo KTs ATo A8s QJs A7s KJo K9s A9o QTs A6s A5s KTo 55 A8o A4s JTs Q9s QJo A7o K8s A3s QTo K9o A2s K7s A5o A6o J9s Q8s JTo A4o K6s 44 K8o T9s K5s Q9o A3o J8s K4s A2o Q7s K7o J9o Q8o K6o T8s K3s Q6s J7s K5o T9o 33 K2s Q5s Q4s 98s K4o J8o T7s Q7o Q3s J6s T8o K3o 97s J5s Q2s 87s Q6o K2o T6s Q5o 98o J7o J4s J3s 96s 22 Q4o 76s T7o T4s T5s 86s 97o J2s Q3o J6o 95s 85s Q2o J5o T6o 87o T3s 75s J4o T2s 65s 96o J3o 93s 86o 54s 94s J2o T5o 76o 74s 64s 84s T4o 92s 95o T3o 85o 65o 63s 53s 73s T2o 83s 82s 75o 43s 94o 93o 54o 74o 52s 62s 84o 64o 72s 92o 42s 53o 83o 32s 73o 82o 63o 43o 52o 62o 72o 42o 32o'.split(' ');
  const idx = new Map(PREFLOP_ORDER.map((c, i) => [c, i]));
  const cum = [];
  { let acc = 0; for (const c of PREFLOP_ORDER) { acc += Cards.codeCombos(c); cum.push(acc / 1326); } }
  const preflopRank = (code) => idx.get(code);                 // 0 = AA … 168 = worst
  const preflopTopPct = (code) => cum[idx.get(code)];          // share of all 1326 combos at least this strong
  const holeTopPct = (hole) => preflopTopPct(Cards.handCode(hole[0], hole[1]));

  return { choose, calc, vsRandom, PREFLOP_ORDER, preflopRank, preflopTopPct, holeTopPct };
})();
